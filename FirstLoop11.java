//Напишите программу FirstLoop.java, которая реализует 
// цикл while для вывода следующего выражения на экран 5 раз.

public class FirstLoop11 {
    public static void main(String[] args) {
        int counter = 0; // initializer
        while (counter < 5){ // condition
            System.out.println("My First While Loop ");
            counter++; // incrementor
        }
    }
}
