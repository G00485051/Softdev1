//  чтобы она использовала составные присваивания.

import java.util.Scanner;

public class ex6 {
    public static void main(String[] args) {
        int result = 1;
        result += 2;
        System.out.println(result);
        result -= 1; ///res = res - 1
         System.out.println(result);
        result *= 2; ///res = res * 2
         System.out.println(result);
        result /= 2; ///res = res / 2
         System.out.println(result);
        result += 8; ///res = res + 8
         System.out.println(result);
        result %= 7; ///res = res % 7
         System.out.println(result);
        
         
    }
}


